import test from "node:test";
import assert from "node:assert/strict";
import { freshGame, act, tick, GROW_TIME } from "../src/game.ts";
test("grow, receive text, sell, and expand apartment", () => {
  const s = freshGame(0);
  act(s, "plant", 0, 0);
  act(s, "water", 0, 0);
  tick(s, GROW_TIME - 1);
  assert.equal(s.slots[0].ready, false);
  tick(s, GROW_TIME);
  act(s, "harvest", 0);
  assert.equal(s.stock, 3);
  const order = s.orders[0];
  act(s, "accept", order.id);
  act(s, "sell", order.id);
  assert.equal(s.cash, 76);
  assert.equal(s.stock, 1);
  assert.equal(s.sales, 1);
  act(s, "sell", order.id);
  assert.equal(s.cash, 76);
  act(s, "upgrade");
  assert.equal(s.slots.length, 2);
  assert.equal(s.cash, 16);
});
test("unwatered plants do not grow and unavailable actions preserve resources", () => {
  const s = freshGame(0);
  act(s, "plant", 0, 0);
  tick(s, 100000);
  assert.equal(s.slots[0].ready, false);
  act(s, "harvest", 0);
  assert.equal(s.stock, 0);
  act(s, "upgrade");
  assert.equal(s.slots.length, 1);
  act(s, "sell", s.orders[0].id);
  assert.equal(s.cash, 40);
  act(s, "decline", s.orders[0].id);
  act(s, "accept", s.orders[0].id);
  assert.equal(s.orders[0].status, "declined");
});
test("save roundtrip preserves growth and limits active messages", () => {
  const s = freshGame(0);
  act(s, "plant", 0);
  act(s, "water", 0, 10);
  const restored = JSON.parse(JSON.stringify(s));
  tick(restored, GROW_TIME + 10);
  assert.equal(restored.slots[0].ready, true);
  for (let t = 100000; t < 500000; t += 30000) tick(restored, t);
  assert.equal(restored.orders.length, 3);
});
